"""Generate src/features/character/rig/rigData.ts from design/character/animation-lab.html.

The animation lab is the source of truth for NIMI's look and motion (design/character/ANIMATION.md).
Its inline script carries every eye, mouth, blush, extra, moon face and orbit ring as SVG strings
(`const D = {...}`) plus the mood names (`const AR`); its markup carries the body and winter layers.
This script copies them verbatim so the React rig never redraws anything by hand.

    python scripts/gen-rig-data.py
"""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LAB = ROOT / "design/character/animation-lab.html"
OUT = ROOT / "src/features/character/rig/rigData.ts"


def js_object(script: str, name: str) -> dict:
    m = re.search(rf"^const {name} = (\{{.*?\}});\s*$", script, re.M)
    if not m:
        raise SystemExit(f"const {name} not found in {LAB.name}")
    return json.loads(m.group(1))


def between(text: str, start: str, end: str) -> str:
    i = text.index(start) + len(start)
    return text[i:text.index(end, i)]


def main() -> None:
    html = LAB.read_text(encoding="utf-8")
    script = html[html.index("<script>"):]
    data = js_object(script, "D")
    ar = js_object(script, "AR")

    # Body: everything inside <g id="body"> before the face. The rim light is split out because
    # the small variant drops it (REFINEMENTS.md §2).
    body = between(html, '<g id="body">', '<g id="face">').strip()
    rim = re.search(r'<path d="M134 82[^>]*/>', body)
    if not rim:
        raise SystemExit("rim light path not found in the body markup")
    body = body.replace(rim.group(0), "")
    face = between(html, '<g id="face">', "</g>\n")
    freckles = "".join(re.findall(r'<path d="M(?:58|142) 151\.5[^>]*/>', face))
    if freckles.count("<path") != 2:
        raise SystemExit("freckle stars not found in the face markup")
    winter = json.loads(re.search(r"els\.winter\.innerHTML=(\".*?\");", script).group(1))

    moods = list(data["moods"].keys())
    out = [
        "// Generated by scripts/gen-rig-data.py from design/character/animation-lab.html — do not edit.",
        "// Re-run the script after the design package changes.",
        "/* eslint-disable */",
        "",
        f"export const MOODS = {json.dumps(moods)} as const;",
        "export type Mood = (typeof MOODS)[number];",
        "",
        "export type MoonPlacement =",
        '  | { mode: "orbit"; face: string; period: number }',
        '  | { mode: "head" | "anchor"; face: string; x: number; y: number; layer: "front" | "back" };',
        "",
        "export interface MoodData {",
        "  e: string;",
        "  m: string;",
        "  b: string;",
        "  o: string;",
        "  moon: MoonPlacement;",
        "}",
        "",
        f"export const MOOD_DATA: Record<Mood, MoodData> = {json.dumps(data['moods'], ensure_ascii=False)};",
        "",
        "/** The lab's own Arabic names for the moods. */",
        f"export const MOOD_NAMES_AR: Record<Mood, string> = {json.dumps(ar, ensure_ascii=False)};",
        "",
        f"export const EYES: Record<string, string> = {json.dumps(data['eyes'], ensure_ascii=False)};",
        f"export const BLINKABLE: Record<string, boolean> = {json.dumps(data['blinkable'])};",
        f"export const MOUTHS: Record<string, string> = {json.dumps(data['mouth'], ensure_ascii=False)};",
        f"export const BLUSH: Record<string, string> = {json.dumps(data['blush'], ensure_ascii=False)};",
        f"export const EXTRAS: Record<string, string> = {json.dumps(data['extras'], ensure_ascii=False)};",
        f"export const MOON_FACES: Record<string, string> = {json.dumps(data['moon'], ensure_ascii=False)};",
        f"export const ORBITS: Record<string, {{ back: string; front: string }}> = {json.dumps(data['orbit'], ensure_ascii=False)};",
        "",
        "/** Feet, body (fill `url(#nbb)`), core shadow, gloss, sparkle, belly — without the rim light. */",
        f"export const BODY_SVG = {json.dumps(body)};",
        f"export const RIM_SVG = {json.dumps(rim.group(0))};",
        f"export const FRECKLES_SVG = {json.dumps(freckles)};",
        f"export const WINTER_SVG = {json.dumps(winter)};",
        "",
    ]
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(moods)} moods)")


if __name__ == "__main__":
    main()
