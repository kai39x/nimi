import { invoke } from "@tauri-apps/api/core";
import type { AppInfo } from "./generated/AppInfo";
import type { BoostPlan } from "./generated/BoostPlan";
import type { BoostPreview } from "./generated/BoostPreview";
import type { BoostResult } from "./generated/BoostResult";
import type { FeedAction } from "./generated/FeedAction";
import type { FeedResult } from "./generated/FeedResult";
import type { FileActionResult } from "./generated/FileActionResult";
import type { HitRect } from "./generated/HitRect";
import type { Meal } from "./generated/Meal";
import type { MediaArt } from "./generated/MediaArt";
import type { MediaCommand } from "./generated/MediaCommand";
import type { MediaState } from "./generated/MediaState";
import type { MonitorInfo } from "./generated/MonitorInfo";
import type { OverlayVisibility } from "./generated/OverlayVisibility";
import type { PocketItem } from "./generated/PocketItem";
import type { ScanProgress } from "./generated/ScanProgress";
import type { ScanResult } from "./generated/ScanResult";
import type { Settings } from "./generated/Settings";
import type { SystemStats } from "./generated/SystemStats";
import type { TrayState } from "./generated/TrayState";
import type { VolumeState } from "./generated/VolumeState";

/**
 * Typed wrappers around Rust commands. Names mirror `src-tauri/src/ipc.rs`; payload types are
 * generated by ts-rs (`npm run ipc:gen`) — never hand-edit `generated/`.
 */

export const appInfo = () => invoke<AppInfo>("app_info");

// Settings
export const getSettings = () => invoke<Settings>("get_settings");
export const setSettings = (settings: Settings) => invoke<Settings>("set_settings", { settings });
export const listMonitors = () => invoke<MonitorInfo[]>("list_monitors");

// Overlay window
export const setHitRects = (rects: HitRect[]) => invoke<void>("set_hit_rects", { rects });
export const getOverlayVisibility = () => invoke<OverlayVisibility>("get_overlay_visibility");
export const getOverlayCovered = () => invoke<boolean>("get_overlay_covered");
export const hideOverlayFor = (seconds: number) => invoke<void>("hide_overlay_for", { seconds });
export const showOverlay = () => invoke<void>("show_overlay");
export const startOverlayDrag = () => invoke<void>("start_overlay_drag");
export const recenterOverlay = () => invoke<void>("recenter_overlay");
export const setOverlayExpanded = (expanded: boolean) =>
  invoke<void>("set_overlay_expanded", { expanded });
export const openSettingsWindow = () => invoke<void>("open_settings_window");
export const focusOverlay = (focus: boolean) => invoke<void>("focus_overlay", { focus });

// Tray
export const setTrayState = (state: TrayState) => invoke<void>("set_tray_state", { state });

// Media (phase 4)
export const getMediaState = () => invoke<MediaState>("get_media_state");
export const getMediaArt = () => invoke<MediaArt | null>("get_media_art");
export const mediaCommand = (command: MediaCommand) => invoke<void>("media_command", { command });
export const openMediaPlayer = (lastApp: string | null) => invoke<void>("open_media_player", { lastApp });
export const getVolume = () => invoke<VolumeState>("get_volume");
export const setVolume = (level: number) => invoke<void>("set_volume", { level });
export const setVolumeMuted = (muted: boolean) => invoke<void>("set_volume_muted", { muted });

// System (phase 5)
export const getSystemStats = () => invoke<SystemStats | null>("get_system_stats");
export const startScan = (drive: string) => invoke<void>("start_scan", { drive });
export const cancelScan = () => invoke<void>("cancel_scan");
export const getScan = (drive: string) => invoke<[ScanProgress | null, ScanResult | null]>("get_scan", { drive });
export const moveFiles = (paths: string[], toDrive: string) => invoke<FileActionResult>("move_files", { paths, toDrive });
export const recycleFiles = (paths: string[]) => invoke<FileActionResult>("recycle_files", { paths });
export const boostPreview = () => invoke<BoostPreview>("boost_preview");
export const runBoost = (plan: BoostPlan) => invoke<BoostResult>("run_boost", { plan });
export const restorePower = () => invoke<void>("restore_power");

// Feeding & pocket (phase 6)
export const feedInfo = (paths: string[]) => invoke<Meal>("feed_info", { paths });
export const feedRun = (action: FeedAction, paths: string[]) => invoke<FeedResult>("feed_run", { action, paths });
export const feedUndo = (token: string) => invoke<void>("feed_undo", { token });
export const openFolder = (path: string) => invoke<void>("open_folder", { path });
export const pocketList = () => invoke<PocketItem[]>("pocket_list");
export const pocketAdd = (paths: string[]) => invoke<PocketItem[]>("pocket_add", { paths });
export const pocketRemove = (ids: string[]) => invoke<PocketItem[]>("pocket_remove", { ids });
export const pocketCopy = (ids: string[]) => invoke<void>("pocket_copy", { ids });
export const pocketRun = (action: FeedAction, ids: string[]) => invoke<FeedResult>("pocket_run", { action, ids });
export const pocketDrag = (ids: string[]) => invoke<void>("pocket_drag", { ids });

